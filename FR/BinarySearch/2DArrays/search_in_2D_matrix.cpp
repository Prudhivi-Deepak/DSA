class Solution{
public:
    bool searchMatrix(vector<vector<int>> &mat, int target){

        // every row is sorted and for every row next row is also sorted
        // so we can apply binary search on index from 0 to m*n m rows, n col
        // index = n*row+col -->  
        // so range is 0 to m*n and apply BS 

        // 3*4 = 12
        // 9 --> [2][0] --> 2 1 --> 2*4+1 --> 9
        // 7 --> 7/4  = 1, 7-(1*4) = 1, 3 = [1][3-1] --> 1*4+3 =7

        // [[-998,-985,-982,-981,-972,-965,-957,-955,-954,-945,-934,-932,-926,-923,-921,-920,-911,-908,-906,-901,-900,-897,-878,-873],[-864,-862,-854,-851,-850,-844,-836,-831,-824,-822,-820,-809,-801,-797,-790,-788,-783,-779,-778,-775,-762,-761,-730,-729],[-728,-721,-719,-718,-714,-711,-709,-706,-699,-696,-683,-680,-673,-670,-667,-658,-649,-648,-639,-619,-610,-608,-606,-590],[-587,-582,-574,-572,-559,-558,-529,-526,-524,-522,-521,-513,-507,-506,-500,-498,-493,-491,-475,-462,-459,-454,-428,-422],[-418,-416,-409,-401,-397,-388,-381,-380,-375,-374,-363,-349,-343,-326,-318,-317,-312,-291,-290,-268,-251,-242,-238,-232],[-226,-223,-220,-211,-207,-205,-203,-202,-201,-193,-187,-184,-183,-180,-174,-170,-168,-153,-147,-138,-137,-129,-123,-120],[-114,-113,-102,-99,-94,-93,-90,-86,-84,-81,-80,-66,-65,-64,-56,-53,-48,-44,-42,-31,-23,-20,-18,-6],
        // [-4,-2,0,3,10,11,27,34,41,54,56,58,59,71,73,85,86,100,105,111,114,133,134,141],
        // [144,146,147,164,169,170,171,180,185,186,195,196,214,229,235,238,241,242,264,272,273,276,281,291],
        // [297,305,307,310,324,330,333,335,339,340,346,364,368,369,383,386,387,391,402,410,422,427,439,441],
        // [445,452,457,459,460,465,471,480,483,489,490,509,519,526,530,534,538,546,554,563,567,575,579,585],
        // [588,589,604,617,620,626,630,635,644,646,648,659,665,671,672,679,680,682,686,690,697,698,701,705],
        // [707,715,717,718,722,729,732,734,736,740,742,743,744,748,750,773,779,793,803,804,810,812,816,822],
        // [825,836,843,853,870,884,887,892,894,896,910,911,919,927,928,931,938,939,968,971,973,975,978,990]]

        int l = 0, m = mat.size(), n = mat[0].size(), r = m*n-1;

        while(l<=r){
            int mid = l+(r-l)/2;

            int row = mid/n, col = mid%n;
            // cout << mid << ", "<< row << " : " << col ;
            // if(row<0 || col<0 || row>=m || col>=n) break;
            // cout << " = " << mat[row][col] << endl;
            if(target == mat[row][col]) return true;
            else if(target < mat[row][col]){
                r = mid-1;
            }
            else l = mid+1;
        }
        
        return false;
    }
};